#!/usr/bin/env python3
# Copy the desktop's "which settings apply" rules out of OrcaSlicer's GUI sources, verbatim.
#
# The desktop settings tabs grey out or hide options that do not apply to the current values
# (e.g. ironing settings while ironing is off). That logic lives in three GUI functions:
#   ConfigManipulation::toggle_print_fff_options   (process)
#   TabFilament::toggle_options                     (filament)
#   TabPrinter::toggle_options                      (printer)
# They are plain config logic wrapped in wxWidgets calls. This script copies their bodies
# unchanged into one translation unit, which compiles against bridge/gui_rules_shim.hpp (small
# stand-ins for the wx/Tab members they use). Keeping the bodies verbatim means an Orca bump
# brings the new rules along; a body that stops compiling against the shim is a build error,
# not a silent divergence.
#
# usage: extract-gui-rules.py <orca-source-dir> <output.cpp>
# SPDX-License-Identifier: AGPL-3.0-or-later
import json
import os
import sys

FUNCTIONS = [
    ("src/slic3r/GUI/ConfigManipulation.cpp",
     "void ConfigManipulation::toggle_print_fff_options(DynamicPrintConfig *config, int variant_index, const bool is_global_config)"),
    ("src/slic3r/GUI/Tab.cpp", "void TabFilament::toggle_options()"),
    ("src/slic3r/GUI/Tab.cpp", "void TabPrinter::toggle_options()"),
]


def function_text(src: str, signature: str, path: str) -> tuple[str, int]:
    start = src.find(signature)
    if start < 0 or src.find(signature, start + 1) >= 0:
        sys.exit(f"extract-gui-rules: expected exactly one '{signature}' in {path}")
    i = src.index("{", start + len(signature))
    depth = 0
    n = len(src)
    while i < n:
        c = src[i]
        if c == "/" and src.startswith("//", i):
            i = src.find("\n", i)
            continue
        if c == "/" and src.startswith("/*", i):
            i = src.index("*/", i) + 2
            continue
        if c in "\"'":
            # Raw strings do not occur in these functions; refuse them rather than mis-parse.
            if c == '"' and i > 0 and src[i - 1] == "R":
                sys.exit(f"extract-gui-rules: raw string literal in {signature}")
            j = i + 1
            while src[j] != c:
                j += 2 if src[j] == "\\" else 1
            i = j + 1
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return src[start:i + 1], src.count("\n", 0, start) + 1
        i += 1
    sys.exit(f"extract-gui-rules: unbalanced braces in {signature}")


def wrapping_detection_types(orca: str) -> list[str]:
    # DevPrinterConfigUtil::support_wrapping_detection reads resources/printers/<model_id>.json at
    # run time; the engine has no resources/, so the answer is baked in here.
    d = os.path.join(orca, "resources", "printers")
    out = []
    for name in sorted(os.listdir(d)):
        if not name.endswith(".json"):
            continue
        try:
            with open(os.path.join(d, name), encoding="utf-8") as f:
                data = json.load(f)
        except (OSError, ValueError):
            continue
        if data.get("00.00.00.00", {}).get("support_wrapping_detection") is True:
            out.append(name[:-5])
    return out


def main() -> None:
    orca, out_path = sys.argv[1], sys.argv[2]
    parts = [
        "// Generated by engine/scripts/extract-gui-rules.py from OrcaSlicer's GUI sources. Do not edit.",
        "// SPDX-License-Identifier: AGPL-3.0-or-later",
        '#include "gui_rules_shim.hpp"',
        "namespace Slic3r { namespace GUI {",
        "bool DevPrinterConfigUtil::support_wrapping_detection(const std::string &type)",
        "{",
        "    static const std::set<std::string> types = {"
        + ", ".join(json.dumps(t) for t in wrapping_detection_types(orca)) + "};",
        "    return types.count(type) > 0;",
        "}",
    ]
    for rel, signature in FUNCTIONS:
        path = os.path.join(orca, rel)
        with open(path, encoding="utf-8") as f:
            text, line = function_text(f.read(), signature, path)
        parts.append(f'#line {line} "{rel}"')
        parts.append(text)
    parts.append("}} // namespace Slic3r::GUI")
    content = "\n".join(parts) + "\n"
    old = None
    if os.path.exists(out_path):
        with open(out_path, encoding="utf-8") as f:
            old = f.read()
    if old != content:
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(content)


if __name__ == "__main__":
    main()
