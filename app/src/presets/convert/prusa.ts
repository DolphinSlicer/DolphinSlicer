/**
 * Custom G-code: rename variables OrcaSlicer calls differently. Variables OrcaSlicer does not
 * have are replaced with their value in the imported config (they only read settings, so the
 * G-code stays the same for this config); lines using one without a known value are commented
 * out, unless that would break an {if} block. OrcaSlicer refuses to slice with unknown variables.
 */
function rewriteGcode(g: string, c: Conv, key: string): string {
  const locals = new Set([...g.matchAll(/\b(?:local|global|var)\s+([A-Za-z_]\w*)/g)].map((m) => m[1]!));
  const replaced = new Map<string, string>(),
    missing = new Set<string>();
  // PrusaSlicer's start G-code checks the printer with M862.3 P "[printer_model]": keep the model name.
  const model = c.context('printer_model');
  const known = (id: string) => ORCA_VAR_SET.has(id) || id in c.schema.options || MACRO_WORDS.has(id) || locals.has(id);
  /** The source value of a variable as a macro literal. */
  const literal = (id: string, index: number, quote: boolean): string | null => {
    const raw = c.context(id);
    if (raw === undefined) return null;
    const els = elementsOf(id, raw);
    const v = els[Math.min(index, els.length - 1)] ?? '';
    const t = META[id]?.t ?? '';
    if (/^Bools?$/.test(t)) return quote ? (v === '1' ? 'true' : 'false') : v;
    if (/^(Strings?|Enums?)$/.test(t)) return quote ? JSON.stringify(v) : v;
    return v.replace(/%$/, '');
  };
  // Strings and regular expressions (after =~ / !~) are skipped, not read as variables.
  const fix = (expr: string, quote: boolean) =>
    expr.replace(
      /("(?:[^"\\]|\\.)*"|[=!]~\s*\/(?:[^/\\]|\\.)*\/)|\b([A-Za-z_]\w*)(?:\s*\[\s*(\d+)\s*\])?/g,
      (m, str: string | undefined, id: string | undefined, idx: string | undefined) => {
        if (str || !id) return m;
        if (id === 'printer_model' && model !== undefined) return quote ? JSON.stringify(model) : model;
        const legacy = /^(.*?)_(\d+)$/.exec(id); // [name_0]
        const base = legacy && !known(id) ? legacy[1]! : id;
        const index = idx !== undefined ? Number(idx) : legacy && base !== id ? Number(legacy[2]) : 0;
        const rest = idx !== undefined ? m.slice(m.indexOf('[')) : '';
        if (known(base)) return m;
        const renamed = RENAMES[base];
        if (renamed && known(renamed)) return renamed + (base !== id ? `_${index}` : '') + rest;
        if (!/^[a-z]/.test(id)) return m;
        const lit = literal(base, index, quote);
        if (lit !== null) {
          replaced.set(base, lit);
          return lit;
        }
        missing.add(base);
        return m;
      },
    );
  const lines = g.split('\n').map((line) => {
    const before = missing.size;
    const out = line.replace(
      /\{([^{}]*)\}|\[([A-Za-z_][\w]*(?:\[[^\]]*\])?)\]/g,
      (m, expr: string | undefined, bracket: string | undefined) =>
        expr !== undefined
          ? `{${fix(expr, true)}}`
          : (() => {
              // [name] prints a value: a renamed variable stays in brackets, a written-in value replaces them.
              const f = fix(bracket!, false);
              const isVar = /^[A-Za-z_]\w*(\[\d+\])?$/.test(f) && known(f.replace(/\[.*$/, '').replace(/_\d+$/, ''));
              return f === bracket ? m : isVar ? `[${f}]` : f;
            })(),
    );
    // A variable without a value here: comment the line out, unless it is part of an {if} block.
    if (missing.size > before && !/\{\s*(if|elsif|else|endif)\b/.test(line)) return `; ${out}`;
    return out;
  });
  if (replaced.size)
    c.note(
      key,
      N_('OrcaSlicer does not have {names}; the values from the imported config were written into the G-code instead ({values}).'),
      'approx',
      { names: [...replaced.keys()].join(', '), values: [...replaced].map(([k, v]) => `${k} = ${v}`).join(', ') },
    );
  if (missing.size)
    c.note(
      key,
      N_(
        'This G-code uses {names}, which OrcaSlicer does not have. Lines using them were turned into comments; check them before printing.',
      ),
      'approx',
      { names: [...missing].join(', ') },
    );
  return lines.join('\n');
}

// ── Putting it together ───────────────────────────────────────────────────────────────────
function sameDefault(key: string, raw: string): boolean {
  const d = META[key]?.d;
  if (d === undefined) return raw === '' || raw === '0' || raw === '""' || /^(0,)*0$/.test(raw);
  const els = elementsOf(key, raw);
  return els.every((e) => e === d || (num(e) === num(d) && Number.isFinite(num(d))));
}

/** Convert one preset; values for other preset types (OrcaSlicer keeps some elsewhere) come back in out. */
function convertOne(src: SourcePreset, schema: TargetSchema, nozzle?: number, shared?: Record<string, string>): Conv {
  const c = new Conv(src, schema, nozzle, shared);
  for (const [key, raw] of Object.entries(src.values)) {
    const rule = RULES[key];
    if (rule) {
      rule(c, key);
      continue;
    }
    if (key in schema.options && !SAME_NAME_DIFFERENT.has(key)) {
      const els = elementsOf(key, raw);
      c.set(key, schema.options[key]!.type.endsWith('s') ? els : (els[0] ?? ''), key);
      continue;
    }
    if (sameDefault(key, raw)) continue;
    // Filament overrides left at "nil" use the printer's value: nothing to carry over.
    if (elementsOf(key, raw).every((v) => v === 'nil')) continue;
    // A feature OrcaSlicer lacks, switched off: OrcaSlicer behaves the same.
    if (/^Bools?$/.test(META[key]?.t ?? '') && elementsOf(key, raw).every((v) => v === '0')) continue;
    c.note(key, N_('OrcaSlicer has no such setting.'), 'dropped');
  }
  if (c.nozzleAssumed)
    c.note(
      'nozzle_diameter',
      N_(
        'Some widths are computed from the nozzle; a 0.4 mm nozzle was assumed. Import the printer preset together with this one to use its nozzle.',
      ),
      'approx',
    );
  return c;
}

/**
 * Convert presets from PrusaSlicer/SuperSlicer files into OrcaSlicer user presets. Presets from
 * the same file are converted together: OrcaSlicer keeps some settings in another preset type
 * (e.g. the extruder clearance is a printer setting there), and print presets use the
 * printer's nozzle.
 */
export function convertPresets(sources: SourcePreset[], schema: TargetSchema, version: string): ConvertedPreset[] {
  const out: ConvertedPreset[] = [];
  const byFile = new Map<string, SourcePreset[]>();
  for (const s of sources) byFile.set(s.file, [...(byFile.get(s.file) ?? []), s]);
  for (const group of byFile.values()) {
    const printer = group.find((s) => s.kind === 'printer');
    const nozzle = printer ? num(elementsOf('nozzle_diameter', printer.values.nozzle_diameter ?? '')[0]) : undefined;
    const shared = Object.assign({}, ...group.map((s) => s.values)) as Record<string, string>;
    const convs = group.map((s) => convertOne(s, schema, Number.isFinite(nozzle) ? nozzle : undefined, shared));
    // Settings OrcaSlicer keeps in another preset type go into that preset, if it came along.
    for (const [i, c] of convs.entries()) {
      for (const kind of ['print', 'filament', 'printer'] as Kind[]) {
        if (kind === group[i]!.kind) continue;
        const extra = c.out[kind];
        const j = group.findIndex((s) => s.kind === kind);
        for (const key of Object.keys(extra)) {
          if (j >= 0) {
            if (!(key in convs[j]!.out[kind])) convs[j]!.out[kind][key] = extra[key];
            continue;
          }
          c.note(
            key,
            kind === 'printer'
              ? N_('OrcaSlicer keeps this in the printer settings; import the printer preset too to carry it over.')
              : kind === 'filament'
                ? N_('OrcaSlicer keeps this in the filament settings; import the filament preset too to carry it over.')
                : N_('OrcaSlicer keeps this in the print settings; import the print preset too to carry it over.'),
            'dropped',
          );
        }
      }
    }
    for (const [i, c] of convs.entries()) {
      const src = group[i]!;
      out.push({
        kind: src.kind,
        name: src.name,
        file: src.file,
        app: src.app,
        notes: c.notes,
        json: {
          ...c.out[src.kind],
          name: src.name,
          from: 'User',
          inherits: '',
          version,
          [`${src.kind}_settings_id`]: src.kind === 'filament' ? [src.name] : src.name,
        },
      });
    }
  }
  return out;
}

/** Is this a PrusaSlicer/SuperSlicer config (or G-code with one), not an OrcaSlicer/Bambu file? */
export function isSourceConfig(name: string, text: string): boolean {
  if (/\.(ini)$/i.test(name)) return true;
  if (/\.(gcode|gco|g)$/i.test(name)) return /^; (?:prusaslicer|superslicer)_config = begin/im.test(text);
  return false;
}
