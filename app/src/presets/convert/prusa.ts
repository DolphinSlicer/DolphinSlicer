// Convert PrusaSlicer and SuperSlicer presets to OrcaSlicer user presets.
//
// OrcaSlicer comes from Bambu Studio, which forked PrusaSlicer and renamed most settings
// (perimeters → wall_loops, fill_density → sparse_infill_density, …). Neither OrcaSlicer nor
// Bambu Studio can read PrusaSlicer configs, so this module maps them:
//   - exact: renamed, or recomputed so the result is the same (a speed given as a % of another
//     speed becomes mm/s; a width given as a % of layer height becomes mm; PrusaSlicer's
//     automatic widths are computed with its own formula);
//   - approximate: OrcaSlicer has a similar but not identical setting → a note says what changed;
//   - not carried over: OrcaSlicer has no such setting → a note, unless the value is the default.
// Source definitions: PrusaSlicer 2.9.7 and SuperSlicer 2.7.61.10 (src/libslic3r/PrintConfig.cpp,
// Preset.cpp), extracted into sourceMeta.json: per key its preset type (s), option type (t),
// label (l) and default (d, where it could be read).
// SPDX-License-Identifier: AGPL-3.0-or-later

import { N_ } from '../../i18n/i18n';
import ORCA_VARS from './orcaVars.json';
import SOURCE_META from './sourceMeta.json';

export type Kind = 'print' | 'filament' | 'printer';
export type SourceApp = 'PrusaSlicer' | 'SuperSlicer';
interface Meta {
  s: Kind;
  t: string;
  l: string;
  d?: string;
}
const META = SOURCE_META as Record<string, Meta>;

export interface SourcePreset {
  name: string;
  kind: Kind;
  values: Record<string, string>;
  file: string;
  app: SourceApp;
}

/** OrcaSlicer's option definitions (public/settings-schema.json). */
export interface TargetSchema {
  options: Record<string, { type: string; label: string; enum_values?: string[]; gui_type?: string }>;
  print: string[];
  filament: string[];
  printer: string[];
}

/** A conversion note. message is English with {placeholders}, to be translated where shown. */
export interface Note {
  key: string;
  label: string;
  message: string;
  vars?: Record<string, string | number>;
  kind: 'approx' | 'dropped';
}

export interface ConvertedPreset {
  kind: Kind;
  name: string;
  /** Where it came from (file name). */
  file: string;
  app: SourceApp;
  /** OrcaSlicer user preset (desktop JSON format). */
  json: Record<string, unknown>;
  notes: Note[];
}

// ── Reading files ────────────────────────────────────────────────────────────────────────
const unescapeC = (s: string) => s.replace(/\\(.)/g, (_, c: string) => ({ n: '\n', r: '\r', t: '\t' })[c] ?? c);

function kindOf(key: string): Kind | undefined {
  return META[key]?.s;
}

/**
 * Presets in a PrusaSlicer/SuperSlicer file: a single preset (.ini from the user folder), a
 * full config export (all three types in one flat .ini), a config bundle ([print:Name] …
 * sections) or the settings block at the end of a G-code file.
 */
export function parseSourceFile(file: string, text: string): SourcePreset[] {
  const base = file.replace(/^.*[\\/]/, '').replace(/\.(ini|gcode|gco|g|bgcode)$/i, '');
  const app: SourceApp =
    /superslicer/i.test(text.slice(0, 400)) || /; superslicer_config = begin/i.test(text) ? 'SuperSlicer' : 'PrusaSlicer';
  const block =
    /^; (?:prusaslicer|superslicer|slic3r\w*)_config = begin\r?$([\s\S]*?)^; (?:prusaslicer|superslicer|slic3r\w*)_config = end/im.exec(
      text,
    );
  if (block) return splitFlat(parseLines(block[1]!.split(/\r?\n/).map((l) => l.replace(/^; ?/, ''))), base, file, app);
  if (/^; generated by (PrusaSlicer|SuperSlicer)/m.test(text.slice(0, 2000))) {
    // G-code without a settings block (binary G-code, or the block was stripped).
    return [];
  }
  const sections = new Map<string, Record<string, string>>();
  let flat: Record<string, string> = {};
  let cur: Record<string, string> = flat;
  for (const line of text.split(/\r?\n/)) {
    const sec = /^\s*\[([^\]]+)\]\s*$/.exec(line);
    if (sec) {
      cur = {};
      sections.set(sec[1]!, cur);
      continue;
    }
    const kv = /^\s*([A-Za-z0-9_]+)\s*=\s?(.*)$/.exec(line);
    if (kv && !line.trimStart().startsWith('#')) cur[kv[1]!] = kv[2]!;
  }
  if (!sections.size) return splitFlat(flat, base, file, app);
  flat = {};
  // Config bundle (or a vendor profile file): resolve "inherits" within the file.
  const out: SourcePreset[] = [];
  const resolve = (kind: Kind, name: string, seen = new Set<string>()): Record<string, string> => {
    const own = sections.get(`${kind === 'printer' ? 'printer' : kind}:${name}`);
    if (!own || seen.has(name)) return {};
    seen.add(name);
    const merged: Record<string, string> = {};
    for (const parent of (own.inherits ?? '')
      .split(';')
      .map((s) => s.trim())
      .filter(Boolean))
      Object.assign(merged, resolve(kind, parent, seen));
    return Object.assign(merged, own);
  };
  for (const id of sections.keys()) {
    const m = /^(print|filament|printer):(.+)$/.exec(id);
    if (!m) continue;
    const kind = m[1] as Kind,
      name = m[2]!;
    if (name.startsWith('*')) continue; // abstract parent presets of vendor files
    const values = resolve(kind, name);
    if (values.printer_technology === 'SLA') continue;
    out.push({ name, kind, values, file, app });
  }
  return out;
}

function parseLines(lines: string[]): Record<string, string> {
  const v: Record<string, string> = {};
  for (const line of lines) {
    const kv = /^\s*([A-Za-z0-9_]+)\s*=\s?(.*)$/.exec(line);
    if (kv) v[kv[1]!] = kv[2]!;
  }
  return v;
}

/** One flat config: a single preset, or all three types (config export, G-code). */
function splitFlat(values: Record<string, string>, base: string, file: string, app: SourceApp): SourcePreset[] {
  if (values.printer_technology === 'SLA') return [];
  const byKind: Record<Kind, Record<string, string>> = { print: {}, filament: {}, printer: {} };
  for (const [k, v] of Object.entries(values)) {
    const kind = kindOf(k);
    if (kind) byKind[kind][k] = v;
  }
  const counts = (Object.keys(byKind) as Kind[]).map((k) => [k, Object.keys(byKind[k]).length] as const);
  const present = counts.filter(([, n]) => n >= 5).map(([k]) => k);
  const single = present.length === 1;
  const settingsId = (kind: Kind) => {
    const raw = values[`${kind}_settings_id`];
    if (!raw) return '';
    // filament_settings_id is a list ("Name";"Other") in multi-material configs.
    return (raw.startsWith('"') ? splitStrings(raw)[0] : raw)?.trim() ?? '';
  };
  return present.map((kind) => ({
    kind,
    file,
    app,
    values: byKind[kind],
    name: settingsId(kind) || (single ? base : `${base} (${kind})`),
  }));
}

/** A coStrings value: "a";"b" with C escapes, or a single unquoted string. */
function splitStrings(raw: string): string[] {
  if (!raw.startsWith('"')) return [unescapeC(raw)];
  const out: string[] = [];
  const re = /"((?:[^"\\]|\\.)*)"/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(raw))) out.push(unescapeC(m[1]!));
  return out;
}

/** The elements of a serialized value, by the source option type. */
export function elementsOf(key: string, raw: string): string[] {
  const t = META[key]?.t ?? '';
  if (t === 'Strings') return splitStrings(raw);
  if (t === 'String') return [unescapeC(raw)];
  if (/s$/.test(t) && t !== 'String') return raw.split(',').map((x) => x.trim());
  return [raw.trim()];
}

// ── Conversion ───────────────────────────────────────────────────────────────────────────
const fmt = (n: number) => String(Number(n.toFixed(4)));
const isPct = (s: string | undefined) => !!s && /%\s*$/.test(s);
const num = (s: string | undefined) => (s === undefined || s === '' || s === 'nil' ? NaN : parseFloat(s));

class Conv {
  readonly out: Record<Kind, Record<string, unknown>> = { print: {}, filament: {}, printer: {} };
  readonly notes: Note[] = [];
  readonly handled = new Set<string>();
  nozzleAssumed = false;
  constructor(
    readonly src: SourcePreset,
    readonly schema: TargetSchema,
    readonly nozzleFromPrinter?: number,
    /** All values of the presets imported together (for custom G-code variables). */
    readonly shared: Record<string, string> = {},
  ) {}

  context(k: string): string | undefined {
    return this.src.values[k] ?? this.shared[k];
  }

  raw(k: string): string | undefined {
    return this.src.values[k];
  }
  els(k: string): string[] {
    const r = this.raw(k);
    return r === undefined ? [] : elementsOf(k, r);
  }
  first(k: string): string | undefined {
    return this.els(k)[0];
  }
  n(k: string): number {
    return num(this.first(k));
  }
  label(k: string): string {
    return this.schema.options[k]?.label || META[k]?.l || k;
  }

  get nozzle(): number {
    const own = num(this.first('nozzle_diameter'));
    if (Number.isFinite(own)) return own;
    if (this.nozzleFromPrinter) return this.nozzleFromPrinter;
    this.nozzleAssumed = true;
    return 0.4;
  }

  /** Set an OrcaSlicer key; routed to the preset type that has it in OrcaSlicer. */
  set(key: string, value: string | string[], from?: string) {
    const def = this.schema.options[key];
    const kind = (['print', 'filament', 'printer'] as Kind[]).find((k) => this.schema[k].includes(key));
    if (!def || !kind) return;
    const vals = Array.isArray(value) ? value : [value];
    // Open choices (suggested values, any number allowed) are not checked.
    if (def.enum_values && !def.gui_type?.endsWith('_open') && !vals.every((v) => def.enum_values!.includes(v))) {
      if (from)
        this.note(from, N_('OrcaSlicer has no “{value}” choice here, so the setting was left at its default.'), 'dropped', {
          value: vals.join(', '),
        });
      return;
    }
    // Vector types end in "s" (floats, strings, points, floats_or_percents, …).
    this.out[kind][key] = def.type.endsWith('s') ? vals : (vals[0] ?? '');
  }

  note(key: string, message: string, kind: Note['kind'], vars?: Note['vars']) {
    this.notes.push({ key, label: this.label(key), message, kind, ...(vars ? { vars } : {}) });
  }

  // ── PrusaSlicer's own value resolution ────────────────────────────────────────────
  layerHeight(): number {
    const v = this.n('layer_height');
    return Number.isFinite(v) ? v : 0.2;
  }
  firstLayerHeight(): number {
    const r = this.first('first_layer_height');
    if (r === undefined) return this.layerHeight();
    return isPct(r) ? (this.layerHeight() * num(r)) / 100 : num(r);
  }

  /** An extrusion width in mm as PrusaSlicer computes it (Flow::extrusion_width). */
  width(key: string): number {
    let r = this.first(key) ?? '0';
    let firstLayer = key === 'first_layer_extrusion_width';
    if (!isPct(r) && num(r) === 0 && key !== 'extrusion_width') {
      r = this.first('extrusion_width') ?? '0';
      firstLayer = false;
    }
    if (isPct(r)) return ((firstLayer ? this.firstLayerHeight() : this.layerHeight()) * num(r)) / 100;
    if (num(r) > 0) return num(r);
    const unity = ['support_material_extrusion_width', 'top_infill_extrusion_width'].includes(key);
    return (unity ? 1 : 1.125) * this.nozzle;
  }

  /** A speed in mm/s; % values are of their base speed, 0 means automatic. */
  speed(key: string, base?: string): { v: number; auto: boolean } {
    const r = this.first(key);
    if (r === undefined) return { v: NaN, auto: false };
    if (isPct(r) && base) {
      const b = this.speed(base, SPEED_BASE[base]);
      return { v: (b.v * num(r)) / 100, auto: b.auto };
    }
    if (num(r) === 0) {
      const m = this.n('max_print_speed');
      return { v: Number.isFinite(m) && m > 0 ? m : 80, auto: true };
    }
    return { v: num(r), auto: false };
  }

  /** An acceleration in mm/s²; 0 means the default acceleration. */
  accel(key: string, base?: string): number {
    const r = this.first(key);
    if (r === undefined) return NaN;
    if (isPct(r) && base) return (this.accel(base) * num(r)) / 100;
    const v = num(r);
    if (v === 0 && key !== 'default_acceleration') {
      const d = this.n('default_acceleration');
      return Number.isFinite(d) ? d : 0;
    }
    return v;
  }
}

/** The speed a "%" speed is relative to, in PrusaSlicer/SuperSlicer. */
const SPEED_BASE: Record<string, string> = {
  external_perimeter_speed: 'perimeter_speed',
  small_perimeter_speed: 'perimeter_speed',
  solid_infill_speed: 'infill_speed',
  top_solid_infill_speed: 'solid_infill_speed',
  support_material_interface_speed: 'support_material_speed',
  first_layer_infill_speed: 'solid_infill_speed',
  first_layer_speed: 'perimeter_speed',
  overhang_speed_0: 'external_perimeter_speed',
  overhang_speed_1: 'external_perimeter_speed',
  overhang_speed_2: 'external_perimeter_speed',
  overhang_speed_3: 'external_perimeter_speed',
  over_bridge_speed: 'bridge_speed',
  internal_bridge_speed: 'bridge_speed',
  gap_fill_speed: 'perimeter_speed',
  thin_walls_speed: 'external_perimeter_speed',
  brim_speed: 'support_material_speed',
};

type Rule = (c: Conv, key: string) => void;

const to =
  (...targets: string[]): Rule =>
  (c, k) => {
    for (const t of targets) c.set(t, c.els(k), k);
  };
const ignore: Rule = () => {};
const enumTo =
  (target: string, map: Record<string, string>, approx: Record<string, string> = {}): Rule =>
  (c, k) => {
    const v = c.first(k) ?? '';
    if (v in approx) {
      c.set(target, approx[v]!, k);
      c.note(k, N_('“{from}” does not exist in OrcaSlicer; “{to}” is used instead.'), 'approx', { from: v, to: approx[v]! });
    } else c.set(target, map[v] ?? v, k);
  };
const speedTo =
  (target: string): Rule =>
  (c, k) => {
    const s = c.speed(k, SPEED_BASE[k]);
    if (!Number.isFinite(s.v)) return;
    c.set(target, fmt(s.v), k);
    if (s.auto)
      c.note(k, N_('PrusaSlicer chose this speed automatically; it is set to the maximum print speed ({speed} mm/s).'), 'approx', {
        speed: fmt(s.v),
      });
  };
const accelTo =
  (target: string, base?: string): Rule =>
  (c, k) => {
    const a = c.accel(k, base);
    if (Number.isFinite(a)) c.set(target, fmt(a), k);
  };
const widthTo =
  (target: string): Rule =>
  (c, k) =>
    c.set(target, fmt(c.width(k)), k);
/** mm or % of the nozzle (PrusaSlicer) → % of the nozzle (OrcaSlicer). */
const nozzlePct =
  (target: string): Rule =>
  (c, k) => {
    const r = c.first(k);
    if (r === undefined) return;
    c.set(target, isPct(r) ? `${fmt(num(r))}%` : `${fmt((num(r) / c.nozzle) * 100)}%`, k);
  };
const bool =
  (target: string, invert = false): Rule =>
  (c, k) =>
    c.set(target, (c.first(k) === '1') !== invert ? '1' : '0', k);
const pctToFactor =
  (target: string): Rule =>
  (c, k) => {
    const v = num(c.first(k));
    if (Number.isFinite(v)) c.set(target, fmt(v / 100), k);
  };
/** 100% = unchanged in OrcaSlicer; PrusaSlicer gives the shrinkage itself (0% = none). */
const shrink =
  (target: string): Rule =>
  (c, k) =>
    c.set(
      target,
      c.els(k).map((v) => `${fmt(100 - num(v))}%`),
      k,
    );
const allPlates =
  (suffix: string): Rule =>
  (c, k) => {
    for (const p of [
      'hot_plate_temp',
      'cool_plate_temp',
      'eng_plate_temp',
      'textured_plate_temp',
      'textured_cool_plate_temp',
      'supertack_plate_temp',
    ])
      c.set(p + suffix, c.els(k), k);
  };
const gcodeTo =
  (target: string): Rule =>
  (c, k) => {
    const v = c.els(k).map((g) => rewriteGcode(g, c, k));
    c.set(target, META[k]?.t === 'Strings' ? v : (v[0] ?? ''), k);
  };

