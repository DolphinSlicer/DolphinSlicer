test('a plain 3MF with parts at different heights puts each of them on the bed', async ({ page }) => {
  await ready(page);
  await page.getByTestId('file-input').setInputFiles({
    name: 'two.3mf',
    mimeType: 'model/3mf',
    buffer: plain3mfOf([
      { size: [20, 20, 10], at: [0, 0, 5] },
      { size: [20, 20, 10], at: [40, 0, 25] },
    ]),
  });
  const list = page.getByTestId('object-list').locator('li');
  await expect(list).toHaveCount(2);
  for (const i of [0, 1]) {
    await list.nth(i).click();
    await expect(page.getByTestId('op-position-2')).toHaveValue('5');
  }
  // The layout of the file is kept: the second box is 40 mm beside the first.
  const xs = await page.evaluate(() =>
    (window as unknown as { __orca: { store: { getState(): { objects: { instances: number[][] }[] } } } }).__orca.store
      .getState()
      .objects.map((o) => o.instances[0]![12]!),
  );
  expect(xs[1]! - xs[0]!).toBeCloseTo(40, 3);
  await page.getByTestId('slice').click();
  await expect(page.getByTestId('preview-legend')).toContainText('Outer wall');
});

test('a 3MF project added to a used plate goes beside what is there', async ({ page }) => {
  await ready(page);
  const { readFileSync } = await import('node:fs');
  const buf = readFileSync(new URL('../../engine/test/fixtures/multi.3mf', import.meta.url));
  const list = page.getByTestId('object-list').locator('li');
  const places = () =>
    page.evaluate(() =>
      (window as unknown as { __orca: { store: { getState(): { objects: { instances: number[][] }[] } } } }).__orca.store
        .getState()
        .objects.map((o) => `${o.instances[0]![12]!.toFixed(1)},${o.instances[0]![13]!.toFixed(1)}`),
    );
  await page.getByTestId('file-input').setInputFiles({ name: 'multi.3mf', mimeType: 'model/3mf', buffer: buf });
  await expect(list).toHaveCount(3);
  const first = await places();
  await page.getByTestId('file-input').setInputFiles({ name: 'multi.3mf', mimeType: 'model/3mf', buffer: buf });
  await expect(list).toHaveCount(6);
  const all = await places();
  expect(all.slice(0, 3)).toEqual(first);
  for (const at of all.slice(3)) expect(first).not.toContain(at);
});

