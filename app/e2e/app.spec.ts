test('a long file name wraps inside its notice', async ({ page }) => {
  await ready(page);
  const name = 'obj_1_george_floyedopus_Vzbot_Vzbot_330_0.4_nozzle_with_a_very_long_file_name.step';
  await page.getByTestId('file-input').setInputFiles({ name, mimeType: 'model/step', buffer: Buffer.from('ISO-10303-21;') });
  const notice = page.getByTestId('notice-warning');
  await expect(notice).toContainText(name);
  // No text runs past the notice's right edge.
  const overflow = await notice.evaluate((n) => {
    const right = n.getBoundingClientRect().right;
    return [...n.querySelectorAll('strong, div')].some(
      (e) => e.getBoundingClientRect().right > right + 0.5 || e.scrollWidth > e.clientWidth + 1,
    );
  });
  expect(overflow).toBe(false);
});

test('slicing keeps the camera where the user left it', async ({ page }) => {
  await ready(page);
  await importStl(page, 'box.stl', boxStl(20, 20, 10));
  const camera = () =>
    page.evaluate(() => {
      const vp = (window as unknown as { __orca: { viewport: { camera: { position: { toArray(): number[] } } } } }).__orca.viewport;
      return vp.camera.position.toArray().map((v) => Math.round(v * 100) / 100);
    });
  test.skip(!(await page.evaluate(() => !!(window as unknown as { __orca?: { viewport?: object } }).__orca?.viewport)), 'no WebGL');
  // Orbit a little so the view differs from the default (starting off the object, so it
  // does not drag the object instead).
  const initial = await camera();
  const box = (await page.locator('canvas').boundingBox())!;
  const x = box.x + box.width * 0.15,
    y = box.y + box.height * 0.85;
  await page.mouse.move(x, y);
  await page.mouse.down();
  await page.mouse.move(x + 120, y - 40, { steps: 5 });
  await page.mouse.up();
  const before = await camera();
  expect(before).not.toEqual(initial);
  await page.getByTestId('slice').click();
  await expect(page.getByTestId('preview-legend')).toContainText('Outer wall');
  expect(await camera()).toEqual(before);
});

test("the view tabs' highlight slides to the chosen tab", async ({ page }) => {
  await ready(page);
  const thumb = page.getByRole('tablist', { name: 'View' }).locator('.seg-thumb');
  const at = async (id: string) => {
    const [a, b] = [await thumb.boundingBox(), await page.getByTestId(id).boundingBox()];
    return Math.abs(a!.x - b!.x) <= 1.5 && Math.abs(a!.width - b!.width) <= 1.5;
  };
  await page.getByTestId('tab-settings').click();
  // On its way, then on the tab.
  expect(await at('tab-settings')).toBe(false);
  await expect.poll(() => at('tab-settings')).toBe(true);
  await page.getByTestId('tab-library').click();
  await expect.poll(() => at('tab-library')).toBe(true);
});
