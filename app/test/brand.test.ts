import { describe, expect, it } from 'vitest';
import { brandGcode } from '../src/engine/brand';

const text = async (s: string) => new Blob(brandGcode(new TextEncoder().encode(s).buffer as ArrayBuffer)).text();

describe('brandGcode', () => {
  it('names DolphinSlicer in the generated-by line, nothing else', async () => {
    const body = '; total layer number: 1\nG1 X1 ; OrcaSlicer\n';
    expect(await text(`; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.5.0 on 2026-11-09 at 10:36:02\n${body}`)).toBe(
      `; HEADER_BLOCK_START\n; generated by DolphinSlicer 2.5.0 on 2026-11-09 at 10:36:02\n${body}`,
    );
    expect(await text('; generated by OrcaSlicer 2.5.0 on 2026-11-09 at 10:36:02\nG28\n')).toBe(
      '; generated by DolphinSlicer 2.5.0 on 2026-11-09 at 10:36:02\nG28\n',
    );
  });
  it('leaves G-code without that line as it is', async () => {
    expect(await text('G28\n; generated by PrusaSlicer 2.8 on x\n')).toBe('G28\n; generated by PrusaSlicer 2.8 on x\n');
  });
});
